const DICTS: Record<Lang, Dict> = { en, uk, ru, de };

/** Word forms: [one, few, many]. English and German use only the first two. */
const WORDS: Record<"track" | "playlist" | "group", Record<Lang, [string, string, string]>> = {
  track: { en: ["track", "tracks", "tracks"], uk: ["трек", "треки", "треків"], ru: ["трек", "трека", "треков"], de: ["Titel", "Titel", "Titel"] },
  playlist: { en: ["playlist", "playlists", "playlists"], uk: ["плейлист", "плейлисти", "плейлистів"], ru: ["плейлист", "плейлиста", "плейлистов"], de: ["Playlist", "Playlists", "Playlists"] },
  group: { en: ["group", "groups", "groups"], uk: ["група", "групи", "груп"], ru: ["группа", "группы", "групп"], de: ["Gruppe", "Gruppen", "Gruppen"] },
};

let current: Lang = "en";

export function detectLanguage(): Lang {
  const raw = String(
    (globalThis as any).Spicetify?.Locale?.getLocale?.() ?? (globalThis as any).Spicetify?.Platform?.Session?.locale ?? (globalThis as any).navigator?.language ?? "en",
  ).toLowerCase();
  const code = raw.slice(0, 2);
  return (["en", "uk", "ru", "de"] as const).find((l) => l === code) ?? "en";
}

/** choice: a fixed language, or "auto" = the language of Spotify itself. */
export function setLanguage(choice: Lang | "auto"): Lang {
  current = choice === "auto" ? detectLanguage() : choice;
  return current;
}
export const language = (): Lang => current;

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const text = DICTS[current][key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

/** "1 track", "3 треки", "12 треків" … */
export function count(n: number, word: "track" | "playlist" | "group"): string {
  const forms = WORDS[word][current];
  let form: string;
  if (current === "uk" || current === "ru") {
    const d = n % 10;
    const h = n % 100;
    form = d === 1 && h !== 11 ? forms[0] : d >= 2 && d <= 4 && (h < 12 || h > 14) ? forms[1] : forms[2];
  } else {
    form = n === 1 ? forms[0] : forms[1];
  }
  return `${n} ${form}`;
}
