#!/usr/bin/env python3
"""Writes the translated messages into install.sh and install.ps1.

The texts live in installer-texts.json (%s = a value filled in at run time).
Run this after changing them; CI fails when the scripts are out of date.
install.ps1 must stay plain ASCII, so its texts are written as \\uXXXX escapes.
"""
import json, pathlib, re

root = pathlib.Path(__file__).resolve().parents[2]
texts = json.loads((root / "scripts/dev/installer-texts.json").read_text(encoding="utf-8"))
LANGS = ["uk", "ru", "de"]


def bash_quote(text: str) -> str:
    return "'" + text.replace("'", "'\\''") + "'"


def bash_block() -> str:
    out = ['  case "$1" in']
    for key, by_lang in texts.items():
        out.append(f"    {key})")
        out.append('      case "${UI_LANG}" in')
        for lang in LANGS:
            out.append(f"        {lang}) fmt={bash_quote(by_lang[lang])} ;;")
        out.append(f"        *) fmt={bash_quote(by_lang['en'])} ;;")
        out.append("      esac ;;")
    out.append('    *) fmt="$1" ;;')
    out.append("  esac")
    return "\n".join(out)


def ps_literal(text: str) -> str:
    # {0}, {1} … instead of %s; everything outside plain ASCII (and the quote) as \uXXXX.
    count = iter(range(100))
    text = re.sub(r"%s", lambda _: "{%d}" % next(count), text)
    escaped = "".join(ch if (32 <= ord(ch) < 127 and ch not in "'\\") else "\\u%04x" % ord(ch) for ch in text)
    return f"[regex]::Unescape('{escaped}')" if "\\u" in escaped else f"'{escaped}'"


def ps_block() -> str:
    out = ["  $Texts = @{"]
    for lang in ["en"] + LANGS:
        out.append(f"    {lang} = @{{")
        for key, by_lang in texts.items():
            out.append(f"      {key} = {ps_literal(by_lang[lang])}")
        out.append("    }")
    out.append("  }")
    return "\n".join(out)


def replace(path: pathlib.Path, block: str) -> None:
    source = path.read_text(encoding="utf-8")
    start, end = "# >>> texts (generated by scripts/dev/gen-installer-texts.py; do not edit by hand)", "# <<< texts"
    pattern = re.compile(r"([ \t]*)" + re.escape(start) + r".*?" + re.escape(end), re.S)
    assert pattern.search(source), f"markers not found in {path}"
    path.write_text(pattern.sub(lambda m: f"{m.group(1)}{start}\n{block}\n{m.group(1)}{end}", source), encoding="utf-8")


replace(root / "install.sh", bash_block())
replace(root / "install.ps1", ps_block())
